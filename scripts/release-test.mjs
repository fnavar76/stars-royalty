let output = ''
function launch() {
  output = ''
  const processHandle = spawn(process.execPath, ['.server-dist/index.js'], launchOptions)
  processHandle.stdout.on('data', d => { output += d })
  processHandle.stderr.on('data', d => { output += d })
  return processHandle
}
let child = launch()
async function stop() {
  child.kill()
  await new Promise(resolveExit => { if (child.exitCode !== null) resolveExit(); else child.once('exit', resolveExit) })
}
async function ready() {
  for (let i = 0; i < 100 && !output.includes('listening'); i++) {
    if (child.exitCode !== null) throw new Error(output)
    await new Promise(r => setTimeout(r, 100))
  }
  assert.match(output, /listening/, 'Servidor no inició')
}
